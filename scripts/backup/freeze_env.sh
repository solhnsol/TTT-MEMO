#!/usr/bin/env bash
# Record the A100 software environment into env/ (committed) for RESTORE.md.
set -euo pipefail
REPO="$(cd "$(dirname "$0")/../.." && pwd)"
mkdir -p "$REPO/env"
cd "$REPO"
for v in .venv .venv-exp02a; do
  [ -x "$v/bin/python" ] || continue
  if command -v uv >/dev/null; then
    uv pip freeze --python "$v/bin/python" > "env/${v#.}.freeze.txt"
  else
    "$v/bin/python" -m pip freeze > "env/${v#.}.freeze.txt"
  fi
done
{
  echo "# generated by scripts/backup/freeze_env.sh"
  echo "python: $(.venv/bin/python -V 2>&1)"
  echo "e2e submodule: $(git -C e2e rev-parse HEAD 2>/dev/null)"
  nvidia-smi --query-gpu=name,driver_version --format=csv,noheader 2>/dev/null | sed 's/^/gpu: /'
  echo "cuda (nvcc): $(nvcc --version 2>/dev/null | tail -1)"
} > env/system.txt
